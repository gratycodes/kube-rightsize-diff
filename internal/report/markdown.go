package report

import (
	"fmt"
	"io"
	"strings"

	"github.com/gratycodes/kube-rightsize-diff/internal/analyze"
)

var statusLabel = map[analyze.Severity]string{
	analyze.Risk:  "🔴 risk",
	analyze.Waste: "🟡 waste",
	analyze.Info:  "⚪ info",
	"ok":          "🟢 ok",
}

// Markdown writes a PR comment. In diff mode it only lists containers
// whose resources or replicas changed in the PR.
func Markdown(w io.Writer, rep analyze.Report) error {
	var b strings.Builder
	t := rep.Totals
	b.WriteString(Marker + "\n")
	b.WriteString("### Kubernetes resource requests check\n\n")
	if t.Containers == 0 {
		if rep.DiffMode {
			b.WriteString("No container requests, limits or replica counts changed in this PR.\n")
		} else {
			b.WriteString("No workloads found in the manifests.\n")
		}
		_, err := io.WriteString(w, b.String())
		return err
	}
	fmt.Fprintf(&b, "**%d at risk · %d over-provisioned** across %d %s.", t.Risks, t.Wastes, t.Containers, plural(rep.DiffMode))
	if rep.DiffMode {
		fmt.Fprintf(&b, " Requested cost **$%.2f → $%.2f/month (%s)**.", t.BaseUSD, t.HeadUSD, signed(t.DeltaUSD))
	} else {
		fmt.Fprintf(&b, " Requested cost **$%.2f/month**.", t.HeadUSD)
	}
	if t.SavingsUSD > 0 {
		fmt.Fprintf(&b, " Trimming requests that exceed the suggestions saves about **$%.2f/month**.", t.SavingsUSD)
	}
	b.WriteString("\n\n")

	b.WriteString("| Status | Workload | Container | CPU request (used → suggested) | Memory request (used → suggested) | Memory limit | Pods | $/month |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|\n")
	for _, r := range rep.Results {
		s := r.Head
		if s == nil {
			s = r.Base
		}
		name := "`" + workload(r) + "`"
		if r.Change != "" {
			name += " " + string(r.Change)
		}
		fmt.Fprintf(&b, "| %s | %s | `%s` | %s | %s | %s | %s | %s |\n",
			statusLabel[r.Status], name, r.Container,
			cell(r, cpu(s.CPURequest), usedCPU(r), cpu(r.SuggestCPU)),
			cell(r, mem(s.MemRequest), usedMem(r), mem(r.SuggestMem)),
			mem(s.MemLimit), pods(r, s), money(r, s))
	}

	var notes []string
	for _, r := range rep.Results {
		for _, f := range r.Findings {
			notes = append(notes, fmt.Sprintf("- **%s** `%s` (`%s`): %s", f.Severity, workload(r), f.Rule, f.Message))
		}
	}
	if len(notes) > 0 {
		fmt.Fprintf(&b, "\n<details><summary>%d findings</summary>\n\n%s\n\n</details>\n", len(notes), strings.Join(notes, "\n"))
	}

	b.WriteString("\n")
	b.WriteString(footer(rep))
	_, err := io.WriteString(w, b.String())
	return err
}

func plural(diff bool) string {
	if diff {
		return "changed containers"
	}
	return "containers"
}

func cell(r analyze.Result, req, used, sug string) string {
	if r.Head == nil {
		return req
	}
	if r.Usage == nil {
		return req + " (no usage data)"
	}
	return fmt.Sprintf("%s (%s → %s)", req, used, sug)
}

func footer(rep analyze.Report) string {
	var parts []string
	if rep.Totals.Unchanged > 0 {
		parts = append(parts, fmt.Sprintf("%d unchanged containers not shown.", rep.Totals.Unchanged))
	}
	if rep.UsageSource != "" {
		u := fmt.Sprintf("Usage: CPU p%s / memory p%s", pct(rep.CPUPct), pct(rep.MemPct))
		if rep.Window != "" {
			u += " over " + rep.Window
		}
		parts = append(parts, u+" from "+rep.UsageSource+".")
	}
	c := rep.Config
	parts = append(parts, fmt.Sprintf("Suggestions add %.0f%% CPU / %.0f%% memory headroom. Prices: $%g per vCPU-hour, $%g per GiB-hour, 730 h/month; costs cover requests only.",
		c.CPUHeadroom*100, c.MemHeadroom*100, c.PricePerVCPUHour, c.PricePerGiBHour))
	return "<sub>" + strings.Join(parts, " ") + " Generated by kube-rightsize-diff.</sub>\n"
}

func pct(p float64) string {
	if p == 0 {
		return "?"
	}
	return fmt.Sprintf("%g", p*100)
}
